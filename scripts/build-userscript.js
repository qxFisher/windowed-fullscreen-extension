#!/usr/bin/env node
/**
 * Generates universal-media-maximizer.user.js from content.js + styles.css,
 * so the userscript never drifts from the extension.
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(rootDir, 'manifest.json'), 'utf8'));
const css = fs.readFileSync(path.join(rootDir, 'styles.css'), 'utf8');
const content = fs.readFileSync(path.join(rootDir, 'content.js'), 'utf8');

const output = `// ==UserScript==
// @name         Universal Adaptive Media Maximizer
// @namespace    https://github.com/matt/myExtensionsForChrome
// @version      ${manifest.version}
// @description  ${manifest.description}
// @author       Matt
// @match        *://*/*
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @run-at       document-idle
// ==/UserScript==
// GENERATED by scripts/build-userscript.js from content.js + styles.css. Do not edit.

(() => {
  'use strict';

  const UVM_CSS = ${JSON.stringify(css)};

  if (typeof GM_addStyle === 'function') {
    GM_addStyle(UVM_CSS);
  } else {
    const styleEl = document.createElement('style');
    styleEl.textContent = UVM_CSS;
    (document.head || document.documentElement).appendChild(styleEl);
  }
})();

${content.trim()}

if (typeof GM_registerMenuCommand === 'function' && window === window.top) {
  GM_registerMenuCommand('Toggle Windowed Fullscreen (Alt+Shift+F)', () => {
    window.__UVM_INSTANCE__?.toggle();
  });
}
`;

fs.writeFileSync(path.join(rootDir, 'universal-media-maximizer.user.js'), output);
console.log('Generated universal-media-maximizer.user.js');
